n = 0  # Inicializa la variable 'n' en 0.

while n <= 50:  # Bucle que se ejecuta mientras 'n' sea menor o igual a 50.
    print(n * n)  # Imprime el cuadrado de 'n'.
    n += 1  # Incrementa 'n' en 1 en cada iteración.

print(
    "----------------------------------------"
)  # Imprime una línea separadora.

for n in range(51):  # Bucle for que recorre la secuencia desde 0 hasta 50.
    print(n * n)  # Imprime el cuadrado del valor actual de 'n'.
