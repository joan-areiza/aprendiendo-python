while True:  # Inicia un ciclo infinito.

    numero = int(
        input("Ingrese un numero: ")
    )  # Pide un entero al usuario en cada vuelta.

    if numero == 111:  # Compara si la entrada es exactamente 111.
        print(
            "Se ingreso el numero 111. Programa finalizado."
        )  # Notifica la salida.
        break  # Rompe el bucle finalizando la ejecución.
